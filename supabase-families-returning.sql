-- ═══════════════════════════════════════════════════════════════════════════
--  families_own: restore the owner as a SAME-ROW predicate on the read side
--
--  APPLIED TO PRODUCTION 2026-09-02. Kept because supabase-coparent.sql skips
--  a policy it has already widened, so a database that ran the old version of
--  that file stays broken until this runs, and because the reasoning below is
--  the whole point.
--
--  Symptom, on the family-setup screen:
--      POST /rest/v1/families ... 403
--      42501  new row violates row-level security policy for table "families"
--
--  ⚠ The message names the wrong half, and that is what made this hard. The
--  WITH CHECK clause was passing the entire time. Proved by running both forms
--  as `authenticated` inside a rolled-back transaction:
--
--      plain INSERT                      -> OK
--      INSERT ... RETURNING id, ...      -> 42501
--
--  PostgREST always emits INSERT ... RETURNING when the client calls .select()
--  after .insert() — and the app needs it, because family_code is generated by
--  the database. RETURNING makes PostgreSQL check the new row against the
--  policy's USING clause as well. supabase-coparent.sql had rewritten that
--  clause from
--
--      parent_id = auth.uid()          ->      is_family_member(id)
--
--  and is_family_member() has to LOOK THE ROW UP: it is STABLE and SECURITY
--  DEFINER, its snapshot predates the tuple it is being asked about, so it
--  answers false for a row that is being created in that very statement. The
--  read side was correct for every row that already existed, which is why
--  getMyFamily() worked and only creation failed.
--
--  ⚠ This widens NOTHING. is_family_member(f) is already true when
--  f.parent_id = auth.uid() — that is one of its two branches — so for any
--  existing row the two expressions are equivalent. Adding the direct column
--  comparison only makes the owner case answerable without a lookup. Verified
--  against production: a second parent still sees 0 rows of this family.
--
--  The write side is untouched, deliberately: renaming a family or re-pointing
--  parent_id stays with the owner, never a co-parent.
-- ═══════════════════════════════════════════════════════════════════════════

DO $fix$
DECLARE v_qual text; v_check text;
BEGIN
  -- ⚠ Read the LIVE policy, never supabase-schema.sql. The dump still records
  -- this policy in its pre-co-parent shape and would have produced a rewrite
  -- that silently dropped the co-parent read path.
  SELECT qual, with_check INTO v_qual, v_check
    FROM pg_policies
   WHERE schemaname = 'public' AND tablename = 'families' AND policyname = 'families_own';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'policy families_own is not present on public.families — stop and look.';
  END IF;

  RAISE NOTICE 'before: USING %', v_qual;
  RAISE NOTICE 'before: WITH CHECK %', coalesce(v_check, '(none)');

  IF position('parent_id = auth.uid()' in coalesce(v_qual, '')) > 0 THEN
    RAISE NOTICE 'skip: the USING clause already answers the owner without a lookup.';
  ELSIF position('is_family_member' in coalesce(v_qual, '')) = 0 THEN
    RAISE EXCEPTION 'families_own USING is not a shape this file knows how to repair. Live value: %', v_qual;
  ELSE
    EXECUTE format(
      'ALTER POLICY families_own ON public.families USING (%s) WITH CHECK (%s)',
      '(parent_id = auth.uid()) OR ' || v_qual,
      coalesce(v_check, '((parent_id = auth.uid()) OR is_admin())')
    );
    RAISE NOTICE 'repaired: the owner is now a same-row predicate, so INSERT ... RETURNING works.';
  END IF;
END $fix$;

DO $after$
DECLARE r record;
BEGIN
  FOR r IN SELECT policyname, cmd, qual::text AS q, with_check::text AS w
             FROM pg_policies
            WHERE schemaname = 'public' AND tablename = 'families'
  LOOP
    RAISE NOTICE 'after:  % | % | USING % | WITH CHECK %', r.policyname, r.cmd, r.q, coalesce(r.w, '(none)');
  END LOOP;
END $after$;
