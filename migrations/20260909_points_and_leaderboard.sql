-- ── 3. the level curve — ONE definition ────────────────────────────────────
-- ⚠ Mirrored in engine/app.js as POINTS_THRESHOLDS. If you change one, change
--   the other: the client draws the progress bar from its copy and the server
--   stores the level the leaderboard shows. They are compared by
--   scripts/test-points-levels.js.
--
-- Sized against measured content: the difficulty mix averages ~2.4 points per
-- question and one grade holds roughly 4,000 questions, so a child who answers
-- everything in their grade once lands around Level 10. Levels 11-12 exist so
-- the child who finishes a grade still has somewhere to go.
CREATE OR REPLACE FUNCTION public.points_level(p_points bigint)
 RETURNS smallint
 LANGUAGE sql
 IMMUTABLE
 PARALLEL SAFE
AS $function$
  SELECT CASE
    WHEN p_points >= 13000 THEN 12
    WHEN p_points >= 11000 THEN 11
    WHEN p_points >=  9300 THEN 10
    WHEN p_points >=  7700 THEN 9
    WHEN p_points >=  6200 THEN 8
    WHEN p_points >=  4800 THEN 7
    WHEN p_points >=  3500 THEN 6
    WHEN p_points >=  2400 THEN 5
    WHEN p_points >=  1500 THEN 4
    WHEN p_points >=   801 THEN 3
    WHEN p_points >=   301 THEN 2
    ELSE 1
  END::smallint;
$function$;

-- ── 4. minting ─────────────────────────────────────────────────────────────
-- The ONLY writer of student_points. Internal: not granted to anon or
-- authenticated, so nothing outside this file can name its own amount.
--
-- Returns the points actually awarded — 0 when the ref has already paid, which
-- is the ordinary case for every question a child revisits.
CREATE OR REPLACE FUNCTION public._award_points(
  p_student uuid,
  p_kind    text,
  p_ref     text,
  p_points  integer
)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_new   bigint;
  v_got   integer;
BEGIN
  IF p_student IS NULL OR p_ref IS NULL OR p_points IS NULL OR p_points <= 0 THEN
    RETURN 0;
  END IF;
  -- A ref is a key, not free text. Anything longer is a caller bug or an
  -- attempt to make the unique index useless by minting unbounded distinct refs.
  IF length(p_ref) > 160 THEN
    RETURN 0;
  END IF;

  INSERT INTO public.student_point_events (student_id, kind, ref, points)
  VALUES (p_student, p_kind, p_ref, p_points)
  ON CONFLICT (student_id, kind, ref) DO NOTHING;

  IF NOT FOUND THEN
    RETURN 0;                      -- already paid for this exact thing
  END IF;

  INSERT INTO public.student_points AS sp (student_id, points, level, updated_at)
  VALUES (p_student, p_points, public.points_level(p_points), now())
  ON CONFLICT (student_id) DO UPDATE
    SET points     = sp.points + excluded.points,
        level      = public.points_level(sp.points + excluded.points),
        updated_at = now()
  RETURNING sp.points INTO v_new;

  v_got := p_points;
  RETURN v_got;
END;
$function$;

REVOKE ALL ON FUNCTION public._award_points(uuid, text, text, integer) FROM PUBLIC;
REVOKE ALL ON FUNCTION public._award_points(uuid, text, text, integer) FROM anon;
REVOKE ALL ON FUNCTION public._award_points(uuid, text, text, integer) FROM authenticated;

-- How many of a kind this student has already been paid for TODAY.
-- ⚠ Mauritius days, not the server's UTC day and not the device clock — the
--   same rule as _muDayKey() in engine/app.js. A child in Mauritius finishing
--   at 21:00 local is on 2026-09-09, not already on the 10th.
CREATE OR REPLACE FUNCTION public._points_today(p_student uuid, p_kind text)
 RETURNS integer
 LANGUAGE sql
 STABLE
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
  SELECT coalesce(count(*), 0)::integer
  FROM public.student_point_events
  WHERE student_id = p_student
    AND kind = p_kind
    AND (created_at AT TIME ZONE 'Indian/Mauritius')::date
        = (now() AT TIME ZONE 'Indian/Mauritius')::date;
$function$;

REVOKE ALL ON FUNCTION public._points_today(uuid, text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public._points_today(uuid, text) FROM anon;
REVOKE ALL ON FUNCTION public._points_today(uuid, text) FROM authenticated;

-- ── 5. what a question is worth ────────────────────────────────────────────
-- Difficulty 1-4 → 1-4 points, read from public.questions, which the client
-- cannot write. A question id the server does not know pays 1: generators in a
-- _manifest.js produce ids that were never imported, and grade9-maths `task`
-- items project to ids that are not rows. Paying those the floor keeps them
-- worth doing without making an unknown id worth more than a known one — which
-- is what would turn "invent an id" into a strategy.
CREATE OR REPLACE FUNCTION public.question_points(p_question_id text)
 RETURNS integer
 LANGUAGE sql
 STABLE
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
  SELECT coalesce(
    (SELECT greatest(1, least(4, q.difficulty))::integer
       FROM public.questions q
      WHERE q.id = p_question_id),
    1);
$function$;

GRANT EXECUTE ON FUNCTION public.question_points(text) TO anon, authenticated, service_role;

-- ── 6. games and timetable ─────────────────────────────────────────────────
-- ⚠ The client sends a KIND and a REF. It never sends an amount, so there is no
--   number for it to inflate. The value and the daily cap both live here.
--
--   game       5 points a finished run, at most 3 paid runs a day (15).
--              Games are a break, not the work: they must never out-earn
--              practice, and the cap is what guarantees that. Game answers
--              still never touch recordAnswer()/_recordDaily() — see CLAUDE.md.
--   timetable 10 points for a planned session actually done, at most 3 a day.
--              The client may call this on every render of the plan; the ledger
--              makes the repeats free.
CREATE OR REPLACE FUNCTION public.award_activity_points(p_kind text, p_ref text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_student uuid := public.current_student_id();
  v_amount  integer;
  v_cap     integer;
  v_awarded integer;
  v_total   bigint;
BEGIN
  IF v_student IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'not_a_student_session');
  END IF;

  IF p_kind = 'game' THEN
    v_amount := 5;  v_cap := 3;
  ELSIF p_kind = 'timetable' THEN
    v_amount := 10; v_cap := 3;
  ELSE
    -- 'question', 'friend' and 'legacy' are minted by their own code paths and
    -- are deliberately unreachable from here.
    RETURN jsonb_build_object('ok', false, 'error', 'unknown_kind');
  END IF;

  IF p_ref IS NULL OR p_ref !~ '^[A-Za-z0-9][A-Za-z0-9:._-]{0,127}$' THEN
    RETURN jsonb_build_object('ok', false, 'error', 'bad_ref');
  END IF;

  IF public._points_today(v_student, p_kind) >= v_cap THEN
    RETURN jsonb_build_object('ok', true, 'awarded', 0, 'note', 'daily_cap');
  END IF;

  v_awarded := public._award_points(v_student, p_kind, p_ref, v_amount);

  SELECT points INTO v_total FROM public.student_points WHERE student_id = v_student;

  RETURN jsonb_build_object(
    'ok', true,
    'awarded', v_awarded,
    'points', coalesce(v_total, 0),
    'level', public.points_level(coalesce(v_total, 0)));
END;
$function$;

GRANT EXECUTE ON FUNCTION public.award_activity_points(text, text) TO anon, authenticated, service_role;

