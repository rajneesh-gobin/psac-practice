-- ═══════════════════════════════════════════════════════════════════════════
--  Points, levels and the (future) global leaderboard
--
--  WHY THIS IS SERVER-SIDE AND student_progress.data->>'xp' IS NOT
--  Today's XP is written by the browser: gainXP() in engine/app.js adds 10 to
--  DB.xp and the whole blob is upserted. get_my_friends() then reads that same
--  client-written number back out. Among the 20 friends a child chose that is
--  fine — nobody is competing with a stranger. A GLOBAL leaderboard makes the
--  number adversarial, and a number the client writes is not a score, it is a
--  suggestion. Anyone can set DB.xp to 999999 from devtools in five seconds.
--
--  So: points are minted here, from facts the server already owns.
--    · which question it was          → student_question_progress (this RPC)
--    · how hard that question is      → public.questions.difficulty (a column)
--    · has it ever paid before        → student_point_events UNIQUE(kind, ref)
--    · who is asking                  → current_student_id(), from the token
--  The client never sends a points amount. It cannot: award_activity_points()
--  takes a KIND and a REF and looks the value up here.
--
--  ⚠ There is NO insert/update/delete grant on either table for anon or
--    authenticated — same reasoning as credit_ledger and chapter_entitlements.
--    A grant that does not exist cannot be re-opened by a later policy mistake.
--
--  ⚠ Safe to rerun. The legacy backfill in §10 is guarded by its own ledger row,
--    so re-running this file cannot pay a child their old XP twice.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── 1. the running total ───────────────────────────────────────────────────
-- One row per student. Denormalised on purpose: the global leaderboard is
-- "ORDER BY points DESC LIMIT 100" against an index, not a sum over a ledger
-- that grows by one row per question answered for ever.
CREATE TABLE IF NOT EXISTS public.student_points (
  student_id   uuid        NOT NULL,
  points       bigint      NOT NULL DEFAULT 0,
  -- What this child had earned under the old flat 10-per-answer scheme, frozen
  -- once and carried forward so nobody is demoted by the change. Kept as its
  -- own column, not folded away, because it is the one part of the total that
  -- was NOT earned under the current rules and a future reset may want it back.
  legacy_bonus integer     NOT NULL DEFAULT 0,
  level        smallint    NOT NULL DEFAULT 1,
  updated_at   timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.student_points ADD COLUMN IF NOT EXISTS points       bigint   DEFAULT 0;
ALTER TABLE public.student_points ADD COLUMN IF NOT EXISTS legacy_bonus integer  DEFAULT 0;
ALTER TABLE public.student_points ADD COLUMN IF NOT EXISTS level        smallint DEFAULT 1;
ALTER TABLE public.student_points ADD COLUMN IF NOT EXISTS updated_at   timestamptz DEFAULT now();

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'student_points_pkey'
                    AND conrelid = 'public.student_points'::regclass) THEN
    ALTER TABLE public.student_points ADD CONSTRAINT student_points_pkey PRIMARY KEY (student_id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'student_points_student_id_fkey'
                    AND conrelid = 'public.student_points'::regclass) THEN
    ALTER TABLE public.student_points ADD CONSTRAINT student_points_student_id_fkey
      FOREIGN KEY (student_id) REFERENCES public.students(id) ON DELETE CASCADE;
  END IF;
END $$;

-- ── 2. the ledger ──────────────────────────────────────────────────────────
-- Every point ever minted, with the natural key that makes minting it twice
-- impossible. This is the whole anti-abuse mechanism; there is no other.
--
--   kind='question'   ref = question id      → a question pays once, EVER
--   kind='game'       ref = game:date:run    → a finished run, capped per day
--   kind='timetable'  ref = entry:date       → a planned session, once per day
--   kind='friend'     ref = other student id → once per PAIR, EVER
--   kind='legacy'     ref = 'v1'             → the one-off carry-over
--
-- ⚠ The friend row is why unfriending and re-adding pays nothing: the ledger
--   row survives the DELETE from student_friends, because it is keyed on the
--   pair and not on the friendship. That was the explicit requirement.
CREATE TABLE IF NOT EXISTS public.student_point_events (
  id         bigint GENERATED BY DEFAULT AS IDENTITY,
  student_id uuid        NOT NULL,
  kind       text        NOT NULL,
  ref        text        NOT NULL,
  points     integer     NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'student_point_events_pkey'
                    AND conrelid = 'public.student_point_events'::regclass) THEN
    ALTER TABLE public.student_point_events ADD CONSTRAINT student_point_events_pkey PRIMARY KEY (id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'student_point_events_unique'
                    AND conrelid = 'public.student_point_events'::regclass) THEN
    ALTER TABLE public.student_point_events ADD CONSTRAINT student_point_events_unique
      UNIQUE (student_id, kind, ref);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'student_point_events_student_id_fkey'
                    AND conrelid = 'public.student_point_events'::regclass) THEN
    ALTER TABLE public.student_point_events ADD CONSTRAINT student_point_events_student_id_fkey
      FOREIGN KEY (student_id) REFERENCES public.students(id) ON DELETE CASCADE;
  END IF;
END $$;

-- ⚠ REPAIR, not decoration. scripts/dump-schema.js does not emit identity or
--   serial definitions — the same gap that makes it emit zero CREATE SEQUENCE
--   statements while a column defaults to nextval(). A database rebuilt FROM
--   supabase-schema.sql therefore gets a plain `bigint NOT NULL` here, and every
--   single insert fails with:
--     null value in column "id" of relation "student_point_events"
--   Production is unaffected (this file created the table there, identity and
--   all) but a fresh build is not, and a fresh build is exactly what the SQL
--   harness does. Repair it in place rather than trusting the dump to be right.
--   ⚠ The real fix belongs in scripts/dump-schema.js; see
--     scripts/sql-tests/known-dump-gaps.sql.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_attribute
                  WHERE attrelid = 'public.student_point_events'::regclass
                    AND attname = 'id'
                    AND attidentity <> '') THEN
    ALTER TABLE public.student_point_events
      ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END $$;

