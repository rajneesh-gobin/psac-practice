-- ─────────────────────────────────────────────────────────────────────────
-- Admin › Activity — where do children and parents actually spend their time?
-- 2026-09-26
--
-- Asked for from the app: "I want to know if parents actually switched to kid
-- mode (from which account), kid clicked chapter practice, and from there
-- didn't click anything."
--
-- ⚠ NOTHING IN THE APP RECORDED THIS. Measured before writing a line: there is
--   no timer, no screen tracking, no `timeSpent` anywhere in engine/. The three
--   event tables that exist answer different questions - login_events (1,580
--   rows) says WHO SIGNED IN and nothing after that, security_events says who
--   was refused, student_point_events says who earned points on a first correct
--   answer. None of them can say a child opened a chapter and left.
--
-- ⚠ TIME IS NOT A COLUMN, IT IS A GAP. A screen is logged on arrival ('screen')
--   and again on departure ('screen_end') carrying the milliseconds spent. The
--   duration is measured client-side with performance.now(), which is MONOTONIC
--   - a device clock that jumps, or is set wrong, cannot produce a negative or
--   a four-hour lesson. created_at stays server-side (now()), so ordering and
--   retention never trust the device at all. This is the same split the rest of
--   the app makes with _muDayKey.
--
-- ⚠ AN ARRIVAL WITH NO DEPARTURE IS THE ANSWER, NOT A BUG. A child who opens a
--   chapter and closes the app leaves a 'screen' with no 'screen_end' - that
--   orphan IS the drop-off this table exists to show. Do not "fix" it by
--   synthesising an end.
--
-- ⚠ WHO, AND ON WHOSE BEHALF, ARE TWO COLUMNS. actor_id is the person holding
--   the device (a parent's auth.users id, or a student id); as_student is the
--   child whose screens are being used. A parent in kid mode is
--   actor_kind='parent' with as_student set - which is exactly the "switched to
--   kid mode, from which account" question, and it is unanswerable from one
--   column.
-- ─────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.activity_events (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Stamped by the trigger below, never by the client.
  family_id  uuid REFERENCES public.families(id) ON DELETE CASCADE,
  actor_kind text NOT NULL CHECK (actor_kind IN ('parent', 'student')),
  actor_id   uuid NOT NULL,
  as_student uuid REFERENCES public.students(id) ON DELETE CASCADE,
  kind       text NOT NULL CHECK (char_length(kind) BETWEEN 1 AND 40),
  ref        text CHECK (char_length(ref) <= 120),
  meta       jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- The timeline, one actor's trail, and one family's trail. All three are read
-- newest-first and nothing here is ever read by anything but the admin panel.
CREATE INDEX IF NOT EXISTS activity_events_created_idx ON public.activity_events (created_at DESC);
CREATE INDEX IF NOT EXISTS activity_events_actor_idx   ON public.activity_events (actor_id, created_at DESC);
CREATE INDEX IF NOT EXISTS activity_events_family_idx  ON public.activity_events (family_id, created_at DESC);

-- ⚠ family_id AND created_at ARE SERVER-DERIVED. A client that could write
--   either could file its rows under another family, or date them into next
--   year and survive every prune. The client sends only actor_kind/actor_id/
--   as_student/kind/ref/meta, and RLS below proves the actor is the caller.
-- ⚠ meta is a small bag (a grade, a subject, a duration), never a document -
--   it is dropped rather than truncated if it arrives oversized, because half a
--   JSON object is worse than none.
CREATE OR REPLACE FUNCTION public.activity_events_stamp()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
BEGIN
  NEW.created_at := now();
  IF NEW.actor_kind = 'student' THEN
    SELECT s.family_id INTO NEW.family_id FROM public.students s WHERE s.id = NEW.actor_id;
  ELSE
    SELECT f.id INTO NEW.family_id FROM public.families f WHERE f.parent_id = NEW.actor_id;
  END IF;
  -- A co-parent is not families.parent_id, so fall back to the child on screen.
  IF NEW.family_id IS NULL AND NEW.as_student IS NOT NULL THEN
    SELECT s.family_id INTO NEW.family_id FROM public.students s WHERE s.id = NEW.as_student;
  END IF;
  IF NEW.meta IS NOT NULL AND char_length(NEW.meta::text) > 500 THEN
    NEW.meta := NULL;
  END IF;
  RETURN NEW;
END $function$;

DROP TRIGGER IF EXISTS activity_events_stamp ON public.activity_events;
CREATE TRIGGER activity_events_stamp
  BEFORE INSERT ON public.activity_events
  FOR EACH ROW EXECUTE FUNCTION public.activity_events_stamp();

ALTER TABLE public.activity_events ENABLE ROW LEVEL SECURITY;

-- ⚠ A CHILD IS `anon` PLUS AN x-student-token, never `authenticated` - a policy
--   granted to authenticated alone is dead for every child in the app.
DROP POLICY IF EXISTS activity_insert_self ON public.activity_events;
CREATE POLICY activity_insert_self ON public.activity_events
  FOR INSERT TO anon, authenticated
  WITH CHECK (
    (actor_kind = 'student' AND actor_id = public.current_student_id())
    OR (actor_kind = 'parent' AND actor_id = auth.uid())
  );

-- ⚠ NO `USING` CLAUSE EXISTS FOR THIS TABLE BELOW ADMIN, AND THE CLIENT MUST
--   NOT ASK FOR ITS ROW BACK. A SELECT policy is evaluated on INSERT whenever
--   the statement carries RETURNING, which PostgREST emits for
--   `.insert().select()` - so a child inserting with `.select()` would be
--   refused by the admin-only read policy. engine/activity.js inserts WITHOUT
--   select() on purpose. See docs/claude/database.md rule 2.
DROP POLICY IF EXISTS activity_select_admin ON public.activity_events;
CREATE POLICY activity_select_admin ON public.activity_events
  FOR SELECT TO authenticated
  USING (public.is_admin());

-- ⚠ THE GRANTS BELOW NARROW, THEY DO NOT WIDEN. Supabase's default privileges
--   hand `anon` and `authenticated` ALL on every new table in public - measured
--   on this table right after it was created: anon held SELECT, INSERT, UPDATE,
--   DELETE, TRUNCATE, REFERENCES and TRIGGER. RLS made that harmless (no policy,
--   no rows), but this is an AUDIT LOG: nothing that writes to it may ever edit
--   or erase it, and that should be true in the grant table, not only in a
--   policy someone could later widen.
REVOKE UPDATE, DELETE, TRUNCATE ON public.activity_events FROM anon, authenticated;
REVOKE SELECT ON public.activity_events FROM anon;
GRANT INSERT ON public.activity_events TO anon, authenticated;
GRANT SELECT ON public.activity_events TO authenticated;

-- A trigger function is only reachable through the trigger, but it is
-- SECURITY DEFINER and inherits the same PUBLIC/anon EXECUTE as any other.
REVOKE ALL ON FUNCTION public.activity_events_stamp() FROM PUBLIC, anon, authenticated;

-- ── Retention ────────────────────────────────────────────────────────────
-- ⚠ A GLOBAL "LAST N" IS NOT RETENTION. One child in one evening writes 30-60
--   rows, so a global cap of 100 would be entirely consumed by whoever used the
--   app most recently and every other family would show nothing. The cap is
--   therefore PER ACTOR (each child, each parent keeps their own last N), with
--   a hard age limit on top so a dormant account does not keep rows for ever.
--
-- ⚠ There is no pg_cron on this database (measured: pg_stat_statements,
--   pgcrypto, plpgsql, supabase_vault, uuid-ossp). This is called by the
--   Worker's 03:00 cron - see workers/api/activity-prune.js.
CREATE OR REPLACE FUNCTION public.prune_activity_events(p_keep int DEFAULT 200, p_days int DEFAULT 30)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
DECLARE v_expired bigint; v_trimmed bigint; v_keep int; v_days int;
BEGIN
  -- service_role (the cron) has no auth.uid(); a signed-in caller must be admin.
  IF auth.uid() IS NOT NULL AND NOT public.is_admin() THEN
    RETURN jsonb_build_object('ok', false, 'error', 'not_authorised');
  END IF;
  v_keep := greatest(coalesce(p_keep, 200), 10);
  v_days := greatest(coalesce(p_days, 30), 1);

  DELETE FROM public.activity_events WHERE created_at < now() - make_interval(days => v_days);
  GET DIAGNOSTICS v_expired = ROW_COUNT;

  WITH ranked AS (
    SELECT id, row_number() OVER (PARTITION BY actor_id ORDER BY created_at DESC, id DESC) AS rn
      FROM public.activity_events
  )
  DELETE FROM public.activity_events e
    USING ranked r
    WHERE e.id = r.id AND r.rn > v_keep;
  GET DIAGNOSTICS v_trimmed = ROW_COUNT;

  RETURN jsonb_build_object('ok', true, 'expired', v_expired, 'trimmed', v_trimmed);
END $function$;

-- ⚠ A new function inherits EXECUTE for PUBLIC, and anon is a member of PUBLIC,
--   so both are named - REVOKE FROM anon alone leaves the `=X` PUBLIC entry.
REVOKE ALL ON FUNCTION public.prune_activity_events(int, int) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.prune_activity_events(int, int) TO authenticated, service_role;
