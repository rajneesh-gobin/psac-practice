'use strict';
// Merge the per-pack family ledgers written by a parallel authoring batch into
// one reviewable record: docs/nce-grade9/question-families.md (+ .json).
//
// WHY A SIDECAR AND NOT QUESTION METADATA
// prompt.md asks for the family, the learning outcome, the variation and the
// targeted misconception to be recorded "in supported metadata or a sidecar
// ledger". There IS no supported metadata: the question factories take a fixed
// field list, duplicated across engine/helpers.js and three server copies, and
// anything else is silently dropped at build time. makeCloze, learnMore and
// subsection were each lost that way. So the only part that lives on the
// question is the part that cannot be dropped — the family, encoded in the id —
// and everything else lives here.
//
//   node scripts/build-family-ledger.js          report only
//   node scripts/build-family-ledger.js --write  write the docs
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'tmp', 'family-expansion');
const OUT_MD = path.join(ROOT, 'docs', 'nce-grade9', 'question-families.md');
const OUT_JSON = path.join(ROOT, 'docs', 'nce-grade9', 'question-families.json');
const WRITE = process.argv.includes('--write');

if (!fs.existsSync(SRC)) { console.error('no ' + SRC); process.exit(1); }
const files = fs.readdirSync(SRC).filter(f => f.endsWith('-ledger.json')).sort();
if (!files.length) { console.error('no ledgers in ' + SRC); process.exit(1); }

const packs = [];
const needs = [];
for (const f of files) {
  let j;
  try { j = JSON.parse(fs.readFileSync(path.join(SRC, f), 'utf8')); }
  catch (e) { console.error('SKIP ' + f + ': ' + e.message); continue; }
  packs.push(j);
  for (const n of (j.needs || [])) needs.push({ pack: j.pack || f, need: n });
}

const LEVEL = { 1: 'Basic', 2: 'Standard', 3: 'Hard', 4: 'Challenge' };
const esc = s => String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim();

let totalFams = 0, totalVars = 0;
const levelTotals = { 1: 0, 2: 0, 3: 0, 4: 0 };
const typeTotals = {};
const lines = [];

lines.push('# NCE Grade 9 — question families');
lines.push('');
lines.push('Generated by `node scripts/build-family-ledger.js --write` from the per-pack');
lines.push('ledgers a parallel authoring batch produced. **Do not hand-edit** — regenerate.');
lines.push('');
lines.push('A *family* is several questions built on ONE context whose variants change what');
lines.push('the pupil has to DO. The family id is the question id minus its `-<variant>`');
lines.push('suffix (`g9sms-fam-007-b` → `g9sms-fam-007`), which is how `_familyOf()` in');
lines.push('`engine/questions_engine.js` keeps variants out of each other\'s way without a');
lines.push('question field that the factories would strip. See `scripts/test-question-families.js`.');
lines.push('');
lines.push('⚠ `variation` is what NEW thinking a variant demands. `misconception` is what its');
lines.push('wrong answers catch. Both are the author\'s assertion, not a measurement — the same');
lines.push('standing as every difficulty label in this repo.');
lines.push('');

for (const p of packs.sort((a, b) => String(a.pack).localeCompare(String(b.pack)))) {
  const fams = p.families || [];
  const vars = fams.flatMap(f => f.variants || []);
  totalFams += fams.length; totalVars += vars.length;
  for (const v of vars) {
    if (levelTotals[v.difficulty] !== undefined) levelTotals[v.difficulty]++;
    typeTotals[v.type || '?'] = (typeTotals[v.type || '?'] || 0) + 1;
  }
  const lv = { 1: 0, 2: 0, 3: 0, 4: 0 };
  for (const v of vars) if (lv[v.difficulty] !== undefined) lv[v.difficulty]++;

  lines.push('## ' + p.pack);
  lines.push('');
  lines.push('**' + fams.length + ' families · ' + vars.length + ' variants** — '
    + [1, 2, 3, 4].map(k => LEVEL[k] + ' ' + lv[k]).join(' · '));
  if (p.notes) { lines.push(''); lines.push('> ' + esc(p.notes)); }
  lines.push('');
  lines.push('| Family | Chapter · subsection | Learning outcome | Context |');
  lines.push('|---|---|---|---|');
  for (const f of fams) {
    lines.push('| `' + esc(f.familyId) + '` | ' + esc(f.chapterId) + (f.subsection ? ' · ' + esc(f.subsection) : '')
      + ' | ' + esc(f.outcome) + ' | ' + esc(f.context) + ' |');
  }
  lines.push('');
  lines.push('<details><summary>Variants — what changes, and what each one catches</summary>');
  lines.push('');
  lines.push('| Id | Level | Type | New thinking required | Misconception caught |');
  lines.push('|---|---|---|---|---|');
  for (const f of fams) {
    for (const v of (f.variants || [])) {
      lines.push('| `' + esc(v.id) + '` | ' + (LEVEL[v.difficulty] || '?') + ' | ' + esc(v.type)
        + ' | ' + esc(v.variation) + ' | ' + esc(v.misconception) + ' |');
    }
  }
  lines.push('');
  lines.push('</details>');
  lines.push('');
}

lines.splice(12, 0,
  '**Batch total: ' + totalFams + ' families, ' + totalVars + ' variants** — '
    + [1, 2, 3, 4].map(k => LEVEL[k] + ' ' + levelTotals[k]).join(' · ')
    + ' · types ' + Object.entries(typeTotals).sort((a, b) => b[1] - a[1]).map(([k, v]) => k + ' ' + v).join(', '),
  '');

// ⚠ Split, not dumped. Half of what the agents recorded is coordinator
// housekeeping that is already done (LOCAL_FILES, the cache-version bump, the
// rebuild); the other half is a defect in the SHIPPED bank that needs a person.
// Rendering both as one table of JSON blobs buries the half that matters.
const HOUSEKEEPING = /local_files|_cache_version|build step|build-questions|brief-erratum|dev.only registration|loader-registration|stale/i;
const isHousekeeping = n => {
  const t = typeof n.need === 'string' ? n.need : JSON.stringify(n.need);
  return HOUSEKEEPING.test(t) && !/content-correction|ambiguous-options|factual|contradict/i.test(t);
};
const content = needs.filter(n => !isHousekeeping(n));
const chores = needs.filter(isHousekeeping);

const field = (o, k) => (o && o[k]) ? String(o[k]) : '';
function renderNeed(n) {
  const d = n.need;
  if (typeof d === 'string') { lines.push(esc(d)); lines.push(''); return; }
  const where = [field(d, 'file'), field(d, 'itemId') || field(d, 'id')].filter(Boolean).join(' · ');
  if (where) lines.push('**' + esc(where) + '**');
  for (const [label, key] of [['Problem', 'problem'], ['Fix', 'fix'],
                              ['Worth checking', 'worthChecking'], ['Note', 'notChanged'], ['Note', 'doNotEdit']]) {
    const v = field(d, key);
    if (v) lines.push('- *' + label + ':* ' + esc(v));
  }
  lines.push('');
}

if (content.length) {
  lines.push('---');
  lines.push('');
  lines.push('## ⚠ Defects in the EXISTING bank — found while authoring, not fixed');
  lines.push('');
  lines.push('Authoring agents may not edit existing files: three sessions write into this');
  lines.push('worktree at once. Each of these is a real defect a child can meet today, found');
  lines.push('while writing the family that teaches the same outcome properly. **Each needs a');
  lines.push('person** — the fix is a content judgement, not a mechanical edit.');
  lines.push('');
  for (const n of content) {
    lines.push('### ' + esc(n.pack));
    lines.push('');
    renderNeed(n);
  }
}

if (chores.length) {
  lines.push('---');
  lines.push('');
  lines.push('## Coordinator housekeeping recorded by the agents');
  lines.push('');
  lines.push('Recorded here for the record; all of it was applied when the batch landed —');
  lines.push('`LOCAL_FILES` synced via `scripts/sync-local-files.js --write`, `_CACHE_VERSION`');
  lines.push('bumped once for the whole batch, and the bundles rebuilt. ' + chores.length + ' item(s).');
  lines.push('');
}

// An optional coordinator addendum: what the COORDINATOR resolved or found
// after the agents finished. Kept in its own file so this doc stays fully
// regenerable while still carrying the half of the story no single agent could
// see — an agent is scoped to one pack and forbidden from editing anything.
const NOTES = path.join(SRC, 'coordinator-notes.md');
if (fs.existsSync(NOTES)) {
  lines.push('---');
  lines.push('');
  lines.push(fs.readFileSync(NOTES, 'utf8').trim());
  lines.push('');
}

const md = lines.join('\n') + '\n';
const json = JSON.stringify({ generated: new Date().toISOString().slice(0, 10), packs, needs }, null, 1);

console.log(md.split('\n').slice(0, 16).join('\n'));
console.log('...');
console.log(totalFams + ' families, ' + totalVars + ' variants across ' + packs.length + ' packs; '
  + needs.length + ' correction(s) recorded.');

if (WRITE) {
  fs.writeFileSync(OUT_MD, md);
  fs.writeFileSync(OUT_JSON, json);
  console.log('wrote ' + path.relative(ROOT, OUT_MD) + ' and ' + path.relative(ROOT, OUT_JSON));
} else {
  console.log('(report only — pass --write to save)');
}
