'use strict';
// Generate image-credits.html from assets/questions/provenance.json.
//
//   node scripts/build-image-credits.js
//
// ⚠ THIS IS A LICENCE OBLIGATION, NOT A COURTESY. Hotlinking a Commons file was
//   arguably only display; copying it into this repo and serving it from our own
//   domain is redistribution, and CC BY and CC BY-SA both require the author,
//   the licence and a link on every copy. Most of the bundled images carry that
//   condition.
//
// ⚠ ONE SOURCE OF TRUTH. provenance.json is the record of the download, captured
//   FORWARD from the Commons API responses that produced each file. Never
//   reconstruct provenance from a local filename: the names are lossy slugs
//   (lowercased, punctuation stripped, spaces hyphenated, truncated to 60), so
//   `adrien-d-epinay1.jpg` can never match "File:Adrien d'Epinay1.jpg" and a
//   generic `ball.jpg` matches an unrelated Commons file. That reverse lookup
//   reports most of the set as "no such file" and reads as "provenance unknown"
//   for images whose licence and author are fully recorded — which is exactly
//   what happened once, and is why there were briefly two credits files.
//
// ⚠ The page is PUBLIC and linked from the landing footer. Do not add a
//   netlify.toml 404 rule for it, and do not hand-edit it — re-run this.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PROV = path.join(ROOT, 'assets', 'questions', 'provenance.json');
const OUT = path.join(ROOT, 'image-credits.html');

if (!fs.existsSync(PROV)) {
  console.error('missing ' + path.relative(ROOT, PROV));
  process.exit(2);
}
const prov = JSON.parse(fs.readFileSync(PROV, 'utf8'));

const esc = s => String(s == null ? '' : s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;')
  .replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const pretty = t => String(t || '').replace(/^File:/, '').replace(/\.[a-z0-9]+$/i, '').replace(/_/g, ' ');

// Commons returns "Artist" as free HTML and it is sometimes a whole template.
const cleanAuthor = a => {
  const s = String(a || '').replace(/\s+/g, ' ').trim();
  if (!s) return '';
  if (/no machine-readable author/i.test(s)) return s.replace(/\s*\(based on copyright claims\)\.?\s*$/i, '');
  return s.length > 130 ? s.slice(0, 127) + '…' : s;
};

const rows = prov.images.slice().sort((a, b) =>
  pretty(a.commonsTitle).localeCompare(pretty(b.commonsTitle)));

const byLicence = {};
for (const m of rows) byLicence[m.licence || '(not stated)'] = (byLicence[m.licence || '(not stated)'] || 0) + 1;
const totalMb = (rows.reduce((a, b) => a + (b.bytes || 0), 0) / 1024 / 1024).toFixed(1);

const body = rows.map(m => {
  const uses = (m.usedBy || []).length;
  const author = cleanAuthor(m.author);
  return `      <tr>
        <td class="thumb"><img src="assets/questions/${esc(m.file)}" alt="" loading="lazy" width="${m.width}" height="${m.height}"></td>
        <td>
          <a href="${esc(m.filePage)}" rel="noopener">${esc(pretty(m.commonsTitle))}</a>
          <div class="meta">${author ? esc(author) : '<span class="dim">author not stated on Commons</span>'}</div>
          <div class="meta dim">${m.width}×${m.height} · ${Math.round((m.bytes || 0) / 1024)} KB · used in ${uses} question${uses === 1 ? '' : 's'}</div>
        </td>
        <td class="lic">${m.licenceUrl
          ? `<a href="${esc(m.licenceUrl)}" rel="noopener">${esc(m.licence || 'see file page')}</a>`
          : esc(m.licence || 'see file page')}</td>
      </tr>`;
}).join('\n');

const summary = Object.entries(byLicence).sort((a, b) => b[1] - a[1])
  .map(([k, v]) => `<li><b>${v}</b> &middot; ${esc(k)}</li>`).join('\n        ');

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Image credits · PSAC Exam Practice</title>
<!-- GENERATED by scripts/build-image-credits.js from assets/questions/provenance.json.
     Do not hand-edit: re-run the script. -->
<style>
  :root { color-scheme: light dark; --bg:#f8fafc; --fg:#0f172a; --dim:#64748b; --line:#e2e8f0; --card:#fff; --link:#4338ca; }
  @media (prefers-color-scheme: dark) {
    :root { --bg:#0f172a; --fg:#e2e8f0; --dim:#94a3b8; --line:#1e293b; --card:#111c33; --link:#a5b4fc; }
  }
  * { box-sizing: border-box; }
  body { margin:0; background:var(--bg); color:var(--fg); font:15px/1.55 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif; }
  .wrap { max-width: 980px; margin: 0 auto; padding: 28px 16px 64px; }
  h1 { font-size: 1.6rem; margin: 0 0 .3em; }
  .lead { color: var(--dim); }
  a { color: var(--link); }
  .panel { background:var(--card); border:1px solid var(--line); border-radius:12px; padding:16px 18px; margin:22px 0; }
  .panel ul { margin:.4em 0 0; padding-left:1.2em; }
  .scroll { overflow-x:auto; -webkit-overflow-scrolling:touch; }
  table { border-collapse: collapse; width:100%; min-width: 560px; background:var(--card);
          border:1px solid var(--line); border-radius:12px; overflow:hidden; }
  th, td { text-align:left; padding:10px 12px; border-bottom:1px solid var(--line); vertical-align:top; }
  th { font-size:.78rem; text-transform:uppercase; letter-spacing:.04em; color:var(--dim); background:transparent; }
  tr:last-child td { border-bottom:0; }
  .thumb { width:96px; }
  .thumb img { width:80px; height:auto; max-height:70px; object-fit:contain; border-radius:6px; display:block; }
  .meta { font-size:.8rem; color:var(--dim); margin-top:2px; }
  .dim { color:var(--dim); }
  .lic { white-space:nowrap; font-size:.85rem; }
  .back { display:inline-block; margin-bottom:14px; }
  @media (max-width: 560px) { .thumb { width:64px; } .thumb img { width:54px; } }
</style>
</head>
<body>
<div class="wrap">
  <a class="back" href="/">&larr; Back to PSAC Exam Practice</a>
  <h1>Image credits</h1>
  <p class="lead">
    ${rows.length} photographs and diagrams in the question bank come from
    <a href="https://commons.wikimedia.org/" rel="noopener">Wikimedia Commons</a>.
    They are stored with the app (${totalMb}&nbsp;MB in total) so that practice works offline
    and so a child on a slow connection is never left waiting on another website.
    Each is listed below with its author and licence. Every other illustration in the
    app is an inline SVG drawn for this project.
  </p>
  <div class="panel">
    <b>Licences used</b>
    <ul>
        ${summary}
    </ul>
    <p class="meta">Images are unmodified apart from being scaled down to the size the app
    displays them at. Scaling is permitted by every licence above, and the author and licence
    travel with each copy, which is what CC&nbsp;BY and CC&nbsp;BY-SA require.</p>
  </div>
  <div class="scroll">
  <table>
    <thead><tr><th></th><th>File &amp; author</th><th>Licence</th></tr></thead>
    <tbody>
${body}
    </tbody>
  </table>
  </div>
  <p class="meta" style="margin-top:22px">
    Names link to the file's page on Wikimedia Commons, which carries the full description
    and licence history. If you are the author of one of these and something here is wrong,
    <a href="/">contact us through the app</a> and it will be corrected or the image removed.
  </p>
</div>
</body>
</html>
`;

fs.writeFileSync(OUT, html);
console.log('  wrote image-credits.html — ' + rows.length + ' images, ' + totalMb + ' MB');
for (const [k, v] of Object.entries(byLicence).sort((a, b) => b[1] - a[1])) {
  console.log('    ' + String(v).padStart(4) + '  ' + k);
}
const noAuthor = rows.filter(r => !cleanAuthor(r.author)).length;
const noLic = rows.filter(r => !r.licence).length;
console.log('  without a stated licence: ' + noLic + '   without a named author: ' + noAuthor);
if (noLic) { console.error('  ⚠ an image with no licence must not ship'); process.exit(1); }
