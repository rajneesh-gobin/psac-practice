'use strict';
// ══════════════════════════════════════════════
//  PSAC Exam Practice - Classrooms & Enrollments
//  Data layer for the teacher role. Follows the Store pattern:
//  every Supabase call lives here, callers get plain objects back.
//
//  Requires: supabase-classrooms-migration.sql
//  Uses _sb (global from supabase.js).
// ══════════════════════════════════════════════

const Classroom = (() => {

  const CLASS_COLS = 'id, teacher_id, name, subject, grade_level, schedule, invite_code, is_active, created_at';

  // ── Create a classroom ─────────────────────────
  // invite_code is generated by the database (gen_invite_code()), not here, so
  // it is guaranteed unique under concurrency.
  async function create(teacherId, name, subject, grade, schedule) {
    if (!_sb || !teacherId) return null;
    if (!name || !name.trim()) return { _error: { message: 'Please enter a class name.' } };

    const { data, error } = await _sb.from('classrooms').insert({
      teacher_id:  teacherId,
      name:        name.trim(),
      subject:     subject || null,
      grade_level: grade ? parseInt(grade) : null,
      schedule:    schedule?.trim() || null,
    }).select(CLASS_COLS).single();

    if (error) { console.error('[Classroom.create]', error.message); return { _error: error }; }
    return data;
  }

  // ── All classrooms owned by a teacher ──────────
  async function getByTeacher(teacherId) {
    if (!_sb || !teacherId) return [];
    const { data, error } = await _sb.from('classrooms')
      .select(CLASS_COLS)
      .eq('teacher_id', teacherId)
      .order('created_at', { ascending: false });
    if (error) { console.warn('[Classroom.getByTeacher]', error.message); return []; }
    return data || [];
  }

  async function update(classroomId, fields) {
    if (!_sb || !classroomId) return false;
    const row = {};
    if (fields.name        !== undefined) row.name        = fields.name.trim();
    if (fields.subject     !== undefined) row.subject     = fields.subject || null;
    if (fields.grade_level !== undefined) row.grade_level = fields.grade_level ? parseInt(fields.grade_level) : null;
    if (fields.schedule    !== undefined) row.schedule    = fields.schedule?.trim() || null;
    if (fields.is_active   !== undefined) row.is_active   = !!fields.is_active;
    if (!Object.keys(row).length) return true;
    const { error } = await _sb.from('classrooms').update(row).eq('id', classroomId);
    if (error) { console.error('[Classroom.update]', error.message); return false; }
    return true;
  }

  async function remove(classroomId) {
    if (!_sb || !classroomId) return false;
    // enrollments + submissions cascade via FK ON DELETE CASCADE
    const { error } = await _sb.from('classrooms').delete().eq('id', classroomId);
    if (error) { console.error('[Classroom.remove]', error.message); return false; }
    return true;
  }

  // ── Join by invite code ────────────────────────
  // Goes through the join_classroom() RPC rather than a direct insert: looking
  // a classroom up by code needs SELECT on classrooms, and granting that
  // publicly would let anyone enumerate every class. The RPC is SECURITY
  // DEFINER and checks that the caller is the student (or their parent).
  async function join(inviteCode, studentId) {
    if (!_sb) return { ok: false, error: 'offline' };
    const code = (inviteCode || '').trim().toUpperCase();
    if (!code)      return { ok: false, error: 'invalid_code' };
    if (!studentId) return { ok: false, error: 'no_student' };

    const { data, error } = await _sb.rpc('join_classroom', {
      p_invite_code: code,
      p_student_id:  studentId,
    });
    if (error) { console.error('[Classroom.join]', error.message); return { ok: false, error: 'server_error' }; }
    return data || { ok: false, error: 'unknown' };
  }

  async function leave(studentId, classroomId) {
    if (!_sb) return false;
    const { error } = await _sb.from('enrollments')
      .update({ is_active: false })
      .eq('student_id', studentId).eq('classroom_id', classroomId);
    return !error;
  }

  // ── Roster for one classroom ───────────────────
  // Returns [{ enrollmentId, joinedAt, isActive, student: {...} }]
  // The embedded students(...) select relies on the FK enrollments.student_id
  // -> students.id. pin/pin_hash are deliberately not requested (and are no
  // longer readable by anon anyway).
  async function getStudents(classroomId) {
    if (!_sb || !classroomId) return [];
    const { data, error } = await _sb.from('enrollments')
      .select('id, joined_at, is_active, students ( id, username, display_name, avatar, grade )')
      .eq('classroom_id', classroomId)
      .eq('is_active', true)
      .order('joined_at', { ascending: true });
    if (error) { console.warn('[Classroom.getStudents]', error.message); return []; }
    return (data || []).map(r => ({
      enrollmentId: r.id,
      joinedAt:     r.joined_at,
      isActive:     r.is_active,
      student:      r.students || null,
    })).filter(r => r.student);
  }

  // ── Classrooms a student belongs to ────────────
  // Works for the student themselves (via their session token) and for their
  // parent - both are covered by the enrollments RLS policies.
  async function getStudentClassrooms(studentId) {
    if (!_sb || !studentId) return [];
    const { data, error } = await _sb.from('enrollments')
      .select('id, joined_at, is_active, classrooms ( ' + CLASS_COLS + ' )')
      .eq('student_id', studentId)
      .eq('is_active', true);
    if (error) { console.warn('[Classroom.getStudentClassrooms]', error.message); return []; }
    return (data || []).map(r => r.classrooms).filter(Boolean);
  }

  // ── Convenience: every student across all of a teacher's classes ───────────
  async function getAllStudentsForTeacher(teacherId) {
    const classes = await getByTeacher(teacherId);
    const out = [];
    for (const c of classes) {
      const roster = await getStudents(c.id);
      roster.forEach(r => out.push({ ...r, classroom: c }));
    }
    return out;
  }

  return {
    create, update, remove,
    getByTeacher,
    join, leave,
    getStudents, getStudentClassrooms,
    getAllStudentsForTeacher,
  };
})();
