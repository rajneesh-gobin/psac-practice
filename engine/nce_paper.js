//  NCE PAPER GENERATION - blueprint-driven, marks-aware, with a mark scheme
//
//  generatePrintablePaper() in app.js builds the PSAC practice paper: a fixed
//  "Section A × 2 marks, Section B × 4 marks" shape with marks as a per-section
//  constant. That is a fair likeness of a PSAC paper and it stays exactly as it
//  is - this module does not touch it.
//
//  It is not remotely an NCE paper. Measured over five years of MES
//  Mathematics papers (docs/nce-grade9/exam-blueprints.md): no named sections
//  at all, ~31 numbered tasks, marks carried per PART and summing to 100,
//  three levels of numbering, shared stimuli, parts that depend on earlier
//  parts, and a progression from 1-mark single steps to 5–7-mark extended
//  problems at the very end.
//
//  ⚠ THE BLUEPRINT IS DATA, NOT CODE. Every subject gets its own entry in
//    BLUEPRINTS, derived from that subject's own papers. Nothing here assumes
//    the Mathematics shape - a subject whose real papers DO have named
//    sections declares `sections` and gets them.
//
//  ⚠ THIS PAPER DOES NOT IMPERSONATE THE MAURITIUS EXAMINATIONS SYNDICATE.
//    The real cover reads "NATIONAL CERTIFICATE OF EDUCATION", carries the MES
//    crest and is © Mauritius Examinations Syndicate. Reproducing that on a
//    generated sheet would be a fake examination paper, and app.js already
//    made this exact call once: its letterhead used to read "Republic of
//    Mauritius - Ministry of Education" and was changed because a printed
//    practice sheet presenting itself as a government document is not undone
//    by small print at the bottom. So this module copies the STRUCTURE that
//    makes a paper useful practice - the marks column, the examiner grid, the
//    numbering, the answer lines, the working space - and says plainly on the
//    cover that it is practice generated by this app.
//
//  ⚠ A PAPER IS NEVER SILENTLY WRONG. If the bank cannot satisfy the
//    blueprint, assemblePaper() still returns the best paper it can AND a
//    populated `warnings` array, and `compliance` reports what it actually
//    achieved against what was asked. Quietly dropping to 92 marks and calling
//    it a 100-mark paper is the failure this is written to avoid.
// ══════════════════════════════════════════════════════════════════════════

