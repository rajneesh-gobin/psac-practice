function markSchemeHtml(paper, opts) {
  const bp = paper.blueprint || opts.blueprint;
  const year = (opts && opts.year) || new Date().getFullYear();
  let n = 0;
  const rows = paper.tasks.map(t => {
    const num = ++n;
    const single = t.parts.length === 1 && t.parts[0].label === 'a';
    const parts = t.parts.map(p => {
      const r = p.response || {};
      let ans;
      if (!A.isAutoMarked(r.kind)) {
        // ⚠ A rubric, never a single "right answer". Pretending one sentence is
        //   the only acceptable response to a drawing or an extended answer is
        //   the thing the brief specifically forbids.
        ans = `<div class="rubric"><b>Marking rubric -</b> ${esc(p.rubric || '')}</div>`;
      } else if (r.kind === 'blanks' || r.kind === 'cells') {
        const alts = (r.answer || []).map(a => esc((Array.isArray(a) ? a[0] : a)));
        const mbc = r.marksByCorrect;
        const rule = mbc
          ? mbc.map((m, i) => `${i} correct &rarr; ${m}`).join(' &middot; ')
          : (r.partial === false
              ? `All ${alts.length} must be correct for the ${p.marks} mark(s); otherwise 0.`
              : `${A.shareMarks(p.marks, alts.length).join(' + ')} across the ${alts.length} blanks.`);
        ans = `<div><b>Answer:</b> ${alts.join(' , ')}</div>
               <div class="pc">Marking: ${rule}</div>`;
      } else if (r.kind === 'multi') {
        ans = `<div><b>Answer:</b> ${(r.answer || []).map(esc).join(' + ')} <i>(all, and only, these)</i></div>`;
      } else {
        const accept = (r.accept || []).filter(Boolean);
        ans = `<div><b>Answer:</b> ${esc(r.answer)}${r.unit ? ' ' + esc(r.unit) : ''}</div>`
            + (accept.length ? `<div class="pc">Also accept: ${accept.map(esc).join(' , ')}</div>` : '')
            + (r.tolerance != null ? `<div class="pc">Tolerance: &plusmn;${r.tolerance}</div>` : '');
      }
      const dep = p.dependsOn
        ? `<div class="pc">Follow-through: award full marks for a correct method applied to the candidate's own answer to ${A.partNotation(p.dependsOn)}.</div>`
        : '';
      // ⚠ A single-part question must NOT print its marks twice. The heading
      //   above already says "Question 4 [1]"; repeating "[1]" on the only part
      //   read on the printed page as two separate marks to award.
      return `<div class="ms-part">
        ${single ? '' : `<div class="ms-head">${A.partNotation(p.label)} <span class="ms-marks">[${p.marks}]</span></div>`}
        <div class="ms-q">${p.prompt}</div>
        ${ans}${dep}
        ${p.explanation ? `<div class="work"><b>Working:</b> ${p.explanation}</div>` : ''}
      </div>`;
    }).join('');
    const msIntro = t.intro ? `<div class="ms-q"><i>${t.intro}</i></div>` : '';
    return `<article class="ms-task"><h3>Question ${num} <span class="ms-marks">[${taskMarks(t)}]</span></h3>${msIntro}${parts}</article>`;
  }).join('');

  const c = paper.compliance || {};
  return `<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Mark Scheme - Grade ${bp.grade} ${esc(bp.subjectName)} ${year}</title>
<style>
  @page { size:A4; margin:14mm 12mm; }
  body { font-family:Arial,Helvetica,sans-serif; color:#111; font-size:10.5pt; line-height:1.4; margin:0; }
  .sheet { max-width:186mm; margin:0 auto; }
  .no-print { background:#166534; color:#fff; border:0; border-radius:6px; padding:9px 18px; font-size:11pt; cursor:pointer; margin-bottom:14px; }
  .head { border:2px solid #111; padding:12px 14px; margin-bottom:14px; }
  .head h1 { font-size:15pt; margin:0 0 4px; }
  .head p { margin:0; color:#444; font-size:10pt; }
  .ms-task { border:1px solid #cbd5e1; border-radius:6px; padding:7px 10px; margin:6px 0; break-inside:avoid; page-break-inside:avoid; }
  .ms-task h3 { margin:0 0 6px; font-size:11.5pt; color:#1e3a5f; }
  .ms-part { border-top:1px dashed #dbe2ea; padding-top:6px; margin-top:6px; }
  .ms-task .ms-part:first-of-type { border-top:0; margin-top:0; padding-top:0; }
  .ms-head { font-weight:bold; }
  .ms-marks { float:right; color:#555; }
  .ms-q { color:#334155; font-size:9.5pt; margin:2px 0 5px; }
  .pc { color:#475569; font-size:9.5pt; margin-top:2px; }
  .rubric { background:#fff7ed; border-left:3px solid #ea580c; padding:6px 8px; margin-top:3px; }
  .work { background:#f8fafc; padding:5px 7px; border-radius:4px; margin-top:4px; font-size:9.5pt; }
  .audit { margin-top:16px; border-top:1px solid #bbb; padding-top:8px; font-size:9pt; color:#555; }
  .warn { background:#fef2f2; border-left:3px solid #dc2626; padding:6px 8px; margin-top:6px; color:#7f1d1d; }
  .stimulus svg, .stimulus img { max-width:60%; height:auto; }
  @media print { .no-print { display:none; } }
</style></head><body><div class="sheet">
<button class="no-print" onclick="window.print()">🖨️ Print / Save mark scheme as PDF</button>
<div class="head">
  <h1>Mark Scheme - Grade ${bp.grade} ${esc(bp.subjectName)} practice paper</h1>
  <p>For parent or teacher use. Keep this separate from the pupil's paper.</p>
  <p>Total: <b>${paper.totalMarks}</b> marks across <b>${paper.tasks.length}</b> questions.</p>
</div>
${rows}
<div class="audit">
  <b>Blueprint check.</b>
  ${c.taskCount}/${c.targetTaskCount} questions &middot;
  ${c.totalMarks}/${c.targetMarks} marks &middot;
  ${c.partCount} mark-bearing parts &middot;
  ${Math.round((c.visualShare || 0) * 100)}% of questions carry a visual (target ${Math.round((c.targetVisualShare || 0) * 100)}%) &middot;
  ${c.manualTasks} drawing/construction task(s) &middot;
  numbering depth ${c.maxDepth} &middot; ${c.dependentParts} dependent part(s).
  ${(paper.warnings || []).map(w => `<div class="warn">⚠ ${esc(w)}</div>`).join('')}
</div>
</div></body></html>`;
}

