const taskMarks = t => t.parts.reduce((s, p) => s + (p.marks || 0), 0);
const isMcqOne = t => t.parts.length === 1 && t.parts[0].marks === 1 &&
  t.parts[0].response && t.parts[0].response.kind === 'choice';
// The opening run is single 1-mark items that are NOT multiple choice - the
// MCQs are gathered into their own consolidated question further down.
const isSingleOneMark = t => t.parts.length === 1 && t.parts[0].marks === 1 && !isMcqOne(t);

// ⚠ Build the paper's ONE multiple-choice question out of several 1-mark MCQ
//   tasks, as every measured year does. The parts keep their source task ids in
//   `sourceIds` so recent-paper history, analytics and the mark scheme can
//   still trace each item back to the bank question it came from - a synthetic
//   task with no provenance would silently break repeat-avoidance.
function buildMcqBlock(items, cfg, chapterId) {
  const letters = 'abcdefghij';
  return {
    id: 'mcq-block:' + items.map(t => t.id).join('+'),
    sourceIds: items.map(t => t.id),
    chapterId: chapterId || items[0].chapterId,
    difficulty: 2,
    type: 'task',
    stimulus: null,
    lead: cfg.lead,
    parts: items.map((t, i) => Object.assign({}, t.parts[0], { label: letters[i] })),
  };
}
// ⚠⚠ A REAL SCIENCE PAPER IS 5-6 QUESTIONS, NOT 41 LOOSE ONES.
//   Every part of these banks is worth one mark (see taskFromQuestion), so an
//   ungrouped paper reaches 50 marks with 41 separate numbered questions while
//   the blueprint asks for 6. The real papers do the opposite: they gather
//   single-mark parts under a handful of numbered questions with (a)(b)(c)
//   sub-parts - Biology 2025 is 6 questions carrying 33 mark-bearing parts.
//   This is the same move buildMcqBlock() already makes for the Q1 MCQ block,
//   generalised to the rest of the paper.
//
// ⚠ GROUPING IS OPT-IN, BY BLUEPRINT. grade9-maths does NOT declare it and is
//   completely unaffected: its bank is authored as real multi-part tasks with
//   real mark values, so grouping there would fabricate structure the author
//   already expressed. Only a bank of adapted single-mark items needs it.
// ⚠ ONLY SAME-CHAPTER PARTS ARE GROUPED. A numbered question in the real paper
//   is about one topic; bundling a circulatory-system part with a photosynthesis
//   part would produce a question no examiner would set.
// ⚠ sourceIds ARE PRESERVED, for the same reason buildMcqBlock preserves them:
//   repeat-avoidance, analytics and the mark scheme all trace a part back to
//   the bank question it came from.
function groupSingleMarkTasks(tasks, cfg) {
  const perQ = Math.max(2, (cfg && cfg.partsPerQuestion) || 6);
  const letters = 'abcdefghijklmnop';
  const single = [], rest = [];
  for (const t of tasks) (t.parts.length === 1 && !t.sourceIds ? single : rest).push(t);

  const byChapter = new Map();
  for (const t of single) {
    if (!byChapter.has(t.chapterId)) byChapter.set(t.chapterId, []);
    byChapter.get(t.chapterId).push(t);
  }

  const grouped = [];
  for (const [chapterId, list] of byChapter) {
    for (let i = 0; i < list.length; i += perQ) {
      const chunk = list.slice(i, i + perQ);
      // A lone leftover stays a question of its own rather than being padded
      // onto an unrelated one.
      if (chunk.length === 1) { grouped.push(chunk[0]); continue; }
      grouped.push({
        id: 'group:' + chunk.map(t => t.id).join('+'),
        sourceIds: chunk.map(t => t.id),
        chapterId,
        subsection: chunk[0].subsection,
        difficulty: chunk[0].difficulty,
        type: 'task',
        stimulus: null,
        parts: chunk.map((t, k) => Object.assign({}, t.parts[0], { label: letters[k] })),
      });
    }
  }
  return rest.concat(grouped);
}

const hasVisual = t => !!(t.stimulus && t.stimulus.html) ||
  t.parts.some(p => /<(svg|img|table)/i.test(p.prompt || ''));
const isManual = t => t.parts.some(p => p.response && !A.isAutoMarked(p.response.kind));

/**
 * Build one paper.
 *
 * @param {object}   o
 * @param {object}   o.blueprint    an entry from BLUEPRINTS
 * @param {object[]} o.tasks        the task bank for this subject
 * @param {number}   o.seed         deterministic; same seed -> same paper
 * @param {string[]} o.recentIds    task ids to avoid while fresh ones remain
 * @returns {{tasks, totalMarks, warnings, compliance}}
 */
function assemblePaper(o) {
  const bp = o.blueprint;
  const rnd = mulberry32(o.seed == null ? (Date.now() & 0xffffffff) : o.seed);
  const warnings = [];
  // ⚠ FRESHNESS IS STIMULUS-AWARE, AND THIS WAS REJECTED ONCE BEFORE.
  //   Keying only on the task id means two different tasks drawing the same
  //   cuboid are both "fresh", and a child meets the same picture on
  //   consecutive papers while every id is new. Measured on a 613-task bank
  //   it made things slightly WORSE (5-paper memorable repeats 33.8% -> 35.1%)
  //   and was not implemented.
  //
  //   ⚠ RE-MEASURED ON THE 671-TASK BANK AND THE ANSWER REVERSED:
  //
  //       variant        5 papers   10 papers   warning-free
  //       id only          11.5%      26.8%        1/5
  //       id + stimulus     5.0%      24.0%        2/5
  //
  //   The reason is that blocking a whole figure family only helps once there
  //   is somewhere else to go. At 63 distinct families it pushed the
  //   assembler onto a smaller pool sooner than blocking one task did; at 104
  //   it has room. A conclusion measured against one bank is not a conclusion
  //   about the code - re-measure it when the bank changes shape.
  //
  //   ⚠ The bank now holds MORE distinct families (104) than five papers ask
  //   for (66 memorable slots), and only 54 were being reached. That is why
  //   this is an assembler change and not another content batch: the depth
  //   exists, the selection could not get at it.
  const _recentIds = new Set(o.recentIds || []);
  const _stimKey = t => (t && t.stimulus && t.stimulus.html)
    ? (t.stimulus.altText || '') + '|' + t.stimulus.html.length : null;
  const _byId = new Map((o.tasks || []).map(t => [t.id, t]));
  const _recentStim = new Set();
  _recentIds.forEach(id => { const k = _stimKey(_byId.get(id)); if (k) _recentStim.add(k); });
  const recent = {
    has(id) {
      if (_recentIds.has(id)) return true;
      const k = _stimKey(_byId.get(id));
      return k ? _recentStim.has(k) : false;
    },
  };
  const bank = (o.tasks || []).filter(t => t && Array.isArray(t.parts) && t.parts.length);

  if (!bank.length) {
    return { tasks: [], totalMarks: 0,
      warnings: ['The task bank is empty - no paper can be built.'],
      compliance: compliance([], bp) };
  }

  // ⚠ Freshness is a PREFERENCE, never a constraint that can shrink the paper.
  //   A paper that is 12 marks short so that nothing repeats is a worse paper
  //   than one that repeats a question, and the brief is explicit about this.
  //   Fresh tasks are simply tried first.
  const fresh = shuffleSeeded(bank.filter(t => !recent.has(t.id)), rnd);
  const stale = shuffleSeeded(bank.filter(t => recent.has(t.id)), rnd);
  const pool = fresh.concat(stale);

  const chosen = [];
  const used = new Set();
  let marks = 0;
  const take = t => { chosen.push(t); used.add(t.id); marks += taskMarks(t); };

  // 1. The opening run of single 1-mark items.
  const singles = pool.filter(t => isSingleOneMark(t) && !used.has(t.id));
  const wantSingles = Math.min(bp.openingSingles, singles.length);
  for (let i = 0; i < wantSingles; i++) take(singles[i]);
  if (wantSingles < bp.openingSingles) {
    warnings.push(`Only ${wantSingles} single 1-mark tasks available; the blueprint opens with ${bp.openingSingles}.`);
  }

  // 1b. The consolidated multiple-choice question.
  let mcqBlock = null;
  if (bp.mcqBlock) {
    const mcqs = pool.filter(t => isMcqOne(t) && !used.has(t.id));
    const want = Math.min(bp.mcqBlock.maxParts, mcqs.length);
    if (want >= bp.mcqBlock.minParts) {
      const items = mcqs.slice(0, want);
      items.forEach(t => used.add(t.id));
      mcqBlock = buildMcqBlock(items, bp.mcqBlock);
      marks += taskMarks(mcqBlock);
    } else {
      warnings.push(`Only ${mcqs.length} single-mark MCQ task(s) available; the blueprint gathers ${bp.mcqBlock.minParts}-${bp.mcqBlock.maxParts} into one question.`);
    }
  }

  // 2. The heavy tail, reserved BEFORE the middle is filled - otherwise the
  //    middle consumes the mark budget and the paper ends on a 2-mark item,
  //    which is not what any of the five years does.
  const tailCfg = bp.extendedTail || { count: 0, minMarks: 5 };
  const tailPool = pool.filter(t => !used.has(t.id) && taskMarks(t) >= tailCfg.minMarks);
  const tail = [];
  for (let i = 0; i < tailCfg.count && i < tailPool.length; i++) {
    tail.push(tailPool[i]); used.add(tailPool[i].id); marks += taskMarks(tailPool[i]);
  }
  if (tail.length < tailCfg.count) {
    warnings.push(`Only ${tail.length} extended task(s) of ${tailCfg.minMarks}+ marks available; the blueprint ends with ${tailCfg.count}.`);
  }

  // 2b. Reserve the drawing/construction task(s) BEFORE the middle, for the
  //     same reason the tail is reserved. Measured: every one of the five years
  //     carries at least one task that must be drawn or constructed, and they
  //     are worth only 1-2 marks - so the middle's "largest task that fits"
  //     preference passes over them every single time and the paper ends up
  //     with none. Left to a warning this was not a near miss: it was 0 of 10
  //     papers, every seed.
  const manualWant = bp.minManualTasks || 0;
  const manualPool = pool.filter(t => !used.has(t.id) && isManual(t));
  let manualGot = 0;
  for (let i = 0; i < manualWant && i < manualPool.length; i++) {
    take(manualPool[i]); manualGot++;
  }
  if (manualGot < manualWant) {
    warnings.push(`Only ${manualGot} drawing/construction task(s) available; every real year has at least ${manualWant}.`);
  }

  // 3. The middle, filled to the mark budget. Chapter weights steer the mix:
  //    a chapter that has already had its share is tried last, so one
  //    well-stocked chapter cannot take over the paper.
  const budget = bp.totalMarks;
  const perChapter = {};
  chosen.concat(tail).forEach(t => { perChapter[t.chapterId] = (perChapter[t.chapterId] || 0) + taskMarks(t); });
  const weightOf = id => (o.chapterWeights && o.chapterWeights[id]) || 1;
  const totalWeight = Object.keys(o.chapterWeights || {}).reduce((s, k) => s + o.chapterWeights[k], 0) || 1;
  const targetFor = id => budget * (weightOf(id) / totalWeight);

  let guard = 0;
  while (marks < budget && guard++ < 5000) {
    const room = budget - marks;
    // Standalone MCQs are excluded: no measured year prints a multiple-choice
    // item as its own numbered question, they are all gathered into the one
    // consolidated question above.
    const cands = pool.filter(t => !used.has(t.id) && taskMarks(t) <= room && !isMcqOne(t));
    if (!cands.length) break;
    // ⚠ The visual share is STEERED, not merely reported. The blueprint says
    //   about one question in four carries a diagram, table or graph; a bank
    //   that is mostly text will hit 100 marks and still look nothing like the
    //   paper. While the paper is below its visual target, a visual candidate
    //   wins a tie - but only a tie, so this can never override the chapter
    //   weights or pull in a question the blueprint did not want.
    const wantVisual = bp.visualTargetPct
      && (chosen.concat(tail).filter(hasVisual).length + (mcqBlock ? 0 : 0))
         < bp.visualTargetPct * (chosen.length + tail.length + 1);
    // Prefer the chapter furthest below its share, then a visual if one is
    // wanted, then the largest task that still fits - large first keeps the
    // paper from filling with 1-mark items.
    cands.sort((x, y) => {
      const dx = targetFor(x.chapterId) - (perChapter[x.chapterId] || 0);
      const dy = targetFor(y.chapterId) - (perChapter[y.chapterId] || 0);
      // ⚠ THE TOLERANCE IS 3, NOT 0.5, AND IT IS THE ONLY LOOSENING THAT HAS
      //   EVER PAID. Two were tried before and both touched SIZE, so both
      //   wrecked the blueprint: freshness above size took the question count
      //   from 33 to 38-46, and a one-mark slack on size still reached 41.
      //   This one decides when two candidates count as EQUALLY OWED by their
      //   chapter, so it moves which chapter contributes a question and never
      //   how big that question is.
      //
      //   Swept over five papers on a 613-task bank. Question count, mark
      //   total and numbering depth were IDENTICAL at every value - which is
      //   the point, and was measured rather than assumed:
      //
      //       tolerance : 0.5    1     2     3     5     8
      //       repeats   : 46.8  44.9  44.2  38.8  41.3  36.4  %
      //       distinct  : 41    43    43    49    44    49
      //       visual    : 29    28    29    30    28    31   % (target 26)
      //       questions : 25-27 25-26 25-26 25-26 25-26 25-26
      //
      //   8 edges out 3 on repeats but pushes the visual share to 31% against
      //   a target of 26 and puts the worst single stimulus back to 8
      //   appearances. 3 is the best trade and is not near a cliff.
      if (Math.abs(dy - dx) > 3) return dy - dx;
      // ⚠ THE STEERING IS SYMMETRIC. It used to prefer a visual candidate while
      //   the paper was BELOW its target and do nothing above it, which was
      //   fine while the bank was mostly text and stopped being fine the
      //   moment 24 figure-carrying tasks were added: the share ran to 32-55%
      //   against a blueprint of 26%. A paper with twice the diagrams of the
      //   real one is off-blueprint in the same way a paper with none is.
      //   Preferring a NON-visual candidate above target costs nothing - it is
      //   still only a tie-break - and measured over ten papers:
      //
      //       one-way    : visual 32-55% (avg 42), memorable repeats 54.8%
      //       symmetric  : visual 26-26% (exactly on target), repeats 44.2%
      //
      //   ⚠ It also cost the numbering depth at first, because 11 of the 20
      //     sub-numbered tasks carried a figure, so capping visuals removed
      //     half the depth-2 pool. The fix was sub-numbering twelve NON-visual
      //     tasks, not loosening this - depth and visual share are separate
      //     blueprint properties and should not have to compete.
      if (hasVisual(x) !== hasVisual(y)) return (wantVisual ? hasVisual(y) : hasVisual(x)) ? 1 : -1;
      // ⚠ Freshness is part of THIS comparison, not only of the pool's initial
      //   order: the sort reorders the pool completely, so a task used on the
      //   last paper could still win on chapter deficit alone. Measured, adding
      //   it took the repeat rate from 56.6% to 47.3%.
      //
      // ⚠ BUT IT RANKS BELOW SIZE, and that ordering is deliberate. Ranked
      //   above size it filled papers with small fresh items: the question
      //   count went from 33 to 38-46 against a blueprint of 31, and the
      //   numbering depth collapsed to 1. Blueprint compliance is what makes
      //   the paper resemble the real one; avoiding a repeat is a preference,
      //   and the brief is explicit that it must never be bought at the
      //   blueprint's expense.
      // ⚠ SIZE IS COMPARED EXACTLY, and freshness only breaks a true tie.
      //   Two looser variants were measured and both were worse:
      //     • freshness ABOVE size  -> repeats 56.6% to 47.3%, but the question
      //       count went from 33 to 38-46 against a blueprint of 31 and the
      //       numbering depth collapsed to 1;
      //     • a one-mark slack on the size comparison -> repeats only 56.6% to
      //       54.0%, and one paper still reached 41 questions.
      //   Blueprint compliance is what makes the paper resemble the real one,
      //   and the brief says freshness must never be bought at its expense.
      // ⚠ PACE, NOT "BIGGEST FIRST". This used to be
      //       if (taskMarks(y) !== taskMarks(x)) return taskMarks(y) - taskMarks(x);
      //   and that kept papers near the blueprint's 31 questions only because
      //   the bank was skewed small - 199 one-mark and 240 two-mark tasks
      //   against 22 at four marks and 2 at seven. It was a proxy for the rule,
      //   not the rule, and it stopped working the moment 48 four-to-seven-mark
      //   tasks were written: the count fell to 25-26 against a target of 31,
      //   because the paper reached 100 marks too soon.
      //
      //   The rule the blueprint actually states is a pace: with M marks still
      //   to place across Q questions still to write, the next question should
      //   be about M/Q marks. Ties still go to the bigger task, so nothing
      //   about the old preference is lost where the pace does not decide.
      //
      //   Measured over five papers on the 613-task bank:
      //       biggest-first : 25-26 questions, repeats 38.8%, 49 distinct
      //       paced        : 31-31 questions, repeats 38.7%, 46 distinct
      //   i.e. the blueprint's own question count for free.
      const left = Math.max(1, (bp.totalMarks - marks));
      const slots = Math.max(1, (bp.targetTaskCount || 31) - chosen.length - tail.length - (mcqBlock ? 1 : 0));
      const pace = left / slots;
      const px = Math.abs(taskMarks(x) - pace), py = Math.abs(taskMarks(y) - pace);
      if (Math.abs(px - py) > 0.001) return px - py;
      if (taskMarks(y) !== taskMarks(x)) return taskMarks(y) - taskMarks(x);
      const fx = recent.has(x.id), fy = recent.has(y.id);
      return (fx === fy) ? 0 : (fx ? 1 : -1);
    });
    const pick = cands[0];
    take(pick);
    perChapter[pick.chapterId] = (perChapter[pick.chapterId] || 0) + taskMarks(pick);
  }

  // Order on the page: the 1-mark openers, then the one multiple-choice
  // question, then the middle, then the heaviest questions last.
  const openers = chosen.slice(0, wantSingles);
  const middle = chosen.slice(wantSingles);
  let paperTasks = openers
    .concat(mcqBlock ? [mcqBlock] : [])
    .concat(middle)
    .concat(tail);
  const total = paperTasks.reduce((s, t) => s + taskMarks(t), 0);
  if (total !== bp.totalMarks) {
    warnings.push(`Paper totals ${total} marks, not ${bp.totalMarks}. The bank cannot currently fill the blueprint exactly.`);
  }
  // ⚠ BOTH DIRECTIONS. Only the "too few" case was checked, so a bank of small
  //   items produced a 44-question paper against a 31-question blueprint and
  //   the generator reported "blueprint satisfied with no warnings". A paper
  //   with half again as many questions as the real one is not compliant, and
  //   saying nothing about it is the overclaiming this module exists to avoid.
  if (paperTasks.length < bp.targetTaskCount * 0.8) {
    warnings.push(`Paper has ${paperTasks.length} questions; the blueprint targets ${bp.targetTaskCount}. The bank has too few multi-mark questions.`);
  } else if (paperTasks.length > bp.targetTaskCount * 1.25) {
    warnings.push(`Paper has ${paperTasks.length} questions; the blueprint targets ${bp.targetTaskCount}. The bank is dominated by low-mark items.`);
  }
  // ⚠ The visual share is a measured feature of the real paper (about one
  //   question in four), not a nice-to-have. A bank of text-only algebra can
  //   hit 100 marks and still be nothing like the paper it claims to imitate.
  const visShare = paperTasks.length ? paperTasks.filter(hasVisual).length / paperTasks.length : 0;
  // ⚠ 0.7, not 0.5. At half the target a paper with 14% visuals against a
  //   measured 26% passed silently - roughly half as many diagrams as the real
  //   paper, which is a difference a candidate would notice on sight. A
  //   threshold loose enough never to complain is not a check.
  if (bp.visualTargetPct && visShare < bp.visualTargetPct * 0.7) {
    warnings.push(`Only ${Math.round(visShare * 100)}% of questions carry a diagram, table or graph; the real paper runs at about ${Math.round(bp.visualTargetPct * 100)}%.`);
  }
  const multiPart = paperTasks.filter(t => t.parts.length > 1).length;
  if (!multiPart) {
    warnings.push('No multi-part question on this paper; every measured year uses (a)/(b) numbering throughout the middle.');
  }
  // ⚠ A block is synthetic, so recent.has(block.id) is always false. Its
  //   sourceIds are what the history actually recorded.
  const idsOnPaper = paperTasks.flatMap(t => t.sourceIds || [t.id]);
  const repeats = idsOnPaper.filter(id => recent.has(id)).length;
  if (repeats) warnings.push(`${repeats} task(s) also appeared in a recent paper - the fresh pool was too small to avoid it.`);
  if (bp.minManualTasks && paperTasks.filter(isManual).length < bp.minManualTasks) {
    warnings.push(`No drawing or construction task on this paper; every real year has at least ${bp.minManualTasks}.`);
  }

  // ⚠ Grouping runs LAST, after selection and ordering, so it cannot change
  //   which questions were chosen - only how they are numbered on the sheet.
  if (bp.groupSingles) {
    paperTasks = groupSingleMarkTasks(paperTasks, bp.groupSingles);
  }

  return { tasks: paperTasks, totalMarks: total, warnings, compliance: compliance(paperTasks, bp) };
}

function compliance(tasks, bp) {
  const parts = tasks.flatMap(t => t.parts);
  const mix = {};
  parts.forEach(p => { mix[p.marks] = (mix[p.marks] || 0) + 1; });
  const pct = {};
  Object.keys(mix).forEach(k => { pct[k] = parts.length ? mix[k] / parts.length : 0; });
  return {
    taskCount: tasks.length,
    targetTaskCount: bp.targetTaskCount,
    totalMarks: tasks.reduce((s, t) => s + taskMarks(t), 0),
    targetMarks: bp.totalMarks,
    partCount: parts.length,
    partMarkCounts: mix,
    partMarkShare: pct,
    targetPartMarkMix: bp.partMarkMix,
    visualTasks: tasks.filter(hasVisual).length,
    visualShare: tasks.length ? tasks.filter(hasVisual).length / tasks.length : 0,
    targetVisualShare: bp.visualTargetPct,
    manualTasks: tasks.filter(isManual).length,
    maxDepth: Math.max(0, ...tasks.flatMap(t => t.parts.map(p => String(p.label).split('.').length))),
    dependentParts: tasks.flatMap(t => t.parts).filter(p => p.dependsOn).length,
  };
}

