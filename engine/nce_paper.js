const esc = s => String(s == null ? '' : s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// The answer line the papers print, reproduced exactly enough to be familiar:
// a pre-printed unknown before the dots, a pre-printed unit after them, the
// marks in brackets at the end. Two unknowns get two blanks on one line.
function answerLine(part) {
  const r = part.response || {};
  const marks = `<span class="pmarks">[${part.marks}]</span>`;
  if (!A.isAutoMarked(r.kind)) {
    // A drawing or written part gets space, not a line to write one word on.
    return `<div class="ans-space" style="height:${Math.max(60, part.marks * 26)}px"></div>
            <div class="ans-row"><span class="spacer"></span>${marks}</div>`;
  }
  // A choice has no answer line - the candidate circles or ticks on the page -
  // so its mark rides on the option block rather than sitting alone below it.
  // A choice has no answer line - the candidate circles or ticks on the page -
  // so its mark rides on the option block rather than sitting alone below it.
  //
  // ⚠ `cells` is the same case and was missed. Table completion is answered IN
  //   the table, whose cells are already printed with dotted gaps; the extra
  //   "Answer: ...., ...., ...." line underneath asked for the same three
  //   values a second time. None of the papers does that.
  if (r.kind === 'choice' || r.kind === 'multi' || r.kind === 'cells') {
    return `<div class="ans-row tight">${marks}</div>`;
  }
  const label = r.label ? `<i>${esc(r.label)}</i> = ` : '';
  // ⚠ A currency goes BEFORE the line and a measurement unit AFTER it, because
  //   that is what the papers print: "Answer: Rs ................" but
  //   "Answer: ................ cm". Rendering "Answer: ........ Rs" looked
  //   right in the HTML and wrong on the page - caught by printing it.
  const prefix = r.prefix ? `${esc(r.prefix)} ` : '';
  const unit = r.unit ? ` ${esc(r.unit)}` : '';
  const n = (r.kind === 'blanks' || r.kind === 'cells') ? (r.answer || []).length : 1;
  const dots = Array.from({ length: n },
    () => `${label}${prefix}<span class="dots"></span>${unit}`).join(', ');
  return `<div class="ans-row"><b>Answer:</b> ${dots} ${marks}</div>`;
}

function partBody(part) {
  const r = part.response || {};
  let html = `<div class="p-prompt">${part.prompt}</div>`;
  if (r.kind === 'choice' && r.variant === 'circle') {
    html += `<div class="inline-choices">${(r.options || []).map(o => `<span class="ic">${o}</span>`).join('')}</div>`;
  } else if (r.kind === 'choice' && r.variant === 'tick') {
    html += `<div class="tick-choices">${(r.options || []).map(o =>
      `<span class="tc">${o} <span class="tickbox"></span></span>`).join('')}</div>`;
  } else if (r.kind === 'choice' || r.kind === 'multi') {
    html += `<div class="mcq">${(r.options || []).map((o, i) =>
      `<div class="mcq-row"><b>${String.fromCharCode(65 + i)}</b><span>${o}</span></div>`).join('')}</div>`;
  }
  // Working space scaled to the marks, as the real papers do: a 1-mark item
  // gets almost none, a 7-mark item gets most of a page.
  const work = part.workingLines != null ? part.workingLines : Math.max(0, (part.marks - 1) * 3);
  if (work && A.isAutoMarked(r.kind)) html += `<div class="work" style="height:${work * 14}px"></div>`;
  html += answerLine(part);
  return html;
}

function taskHtml(task, number) {
  // Order on the page: the stem, then the figure it introduces, then the
  // parts. Printing the figure first put a diagram above the sentence that
  // explains what it is.
  const intro = task.intro ? `<div class="t-intro">${task.intro}</div>` : '';
  const stim = task.stimulus && task.stimulus.html
    ? `<div class="stimulus" role="img" aria-label="${esc(task.stimulus.altText || '')}">${task.stimulus.html}</div>` : '';
  const single = task.parts.length === 1 && task.parts[0].label === 'a';
  // ⚠ THE .pbody WRAPPER IS ALWAYS THERE, even for a single-part task.
  //   `.part` is display:flex, so without it every child of the part - the
  //   working space and the answer box among them - becomes a flex ITEM and
  //   shrinks to its content width. An empty working div then collapses to a
  //   2px vertical line. Printed, that meant a 5-mark extended question with
  //   no room to work in and a "drawing" task with no box to draw in. It was
  //   invisible in the HTML and obvious on the page.
  const parts = task.parts.map(p =>
    `<div class="part">${single ? '' : `<span class="plabel">${A.partNotation(p.label)}</span>`}<div class="pbody">${partBody(p)}</div></div>`
  ).join('');
  const lead = task.lead ? `<div class="tlead">${task.lead}</div>` : '';
  return `<div class="task${task.lead ? ' splittable' : ''}"><div class="tnum">${number}.</div><div class="tbody">${lead}${intro}${stim}${parts}</div></div>`;
}

